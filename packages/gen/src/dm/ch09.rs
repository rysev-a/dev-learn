// 5. Обход в ширину
fn bfs() -> SceneSpec {
    const N: [Pt; 6] = [(60.0, 76.0, "S"), (130.0, 36.0, "1"), (130.0, 116.0, "1"), (210.0, 36.0, "2"), (210.0, 116.0, "2"), (290.0, 76.0, "3")];
    const E: [(usize, usize); 6] = [(0, 1), (0, 2), (1, 3), (2, 4), (3, 5), (4, 5)];
    const LAYER: [usize; 6] = [0, 1, 1, 2, 2, 3];
    const COL: [Tone; 4] = [G, B, Y, R];
    const QUEUE: [&[&str]; 4] = [&["S"], &["1", "1"], &["1", "2"], &["2", "2"]];
    spec(
        &["Ширина", "Волна", "Очередь", "Стек против очереди"],
        &[
            "Второй способ — обход в ширину: сначала все ближние, потом дальние",
            "Из старта посещаем всех соседей, потом соседей соседей — волна расходится кругами по воде",
            "Чтобы волна не сбивалась, нужна очередь: «первым пришёл — первым ушёл» держит порядок по расстоянию",
            "Стек и очередь — единственная разница в коде, а поведение алгоритмов радикально разное",
        ],
        steps(4, |k| {
            let wave = (1..=2).contains(&k);
            // граф бледнеет, когда появляется очередь, и уходит вместе с волной на последнем шаге
            let o = if k == 2 { 0.35 } else { 1.0 };
            let nl = |i: usize| if wave { (COL[LAYER[i]], o) } else { (M, o) };
            let el = |_: usize| if wave { (G, o) } else { (M, o) };
            let mut f = Frame::new();
            if k <= 2 {
                if wave {
                    f = f.with_all((1..4).map(|l| circle(format!("r{l}"), 60.0, 76.0, l as f64 * 76.0 + 8.0).dash().opacity(0.4).width(1.2)));
                }
                f = f.with_all(graph("g", &N, &E, 13.0, 10.5, false, nl, el));
            }
            match k {
                1 => f.with(mt("t1", 180.0, 152.0, "круг 0 → 1 → 2 → 3", 11.0).tone(G)),
                2 => f
                    .with(tx("ql", 180.0, 30.0, "очередь", 9.5))
                    .with_all(QUEUE.iter().enumerate().flat_map(|(i, q)| q.iter().enumerate().map(move |(j, v)| pill(&format!("q{i}-{j}"), 150.0 + j as f64 * 36.0, 46.0 + i as f64 * 24.0, 30.0, 18.0, v, B, 9.0))))
                    .with(mt("t2", 180.0, 152.0, "вынули слева, добавили справа", 11.0).tone(B)),
                3 => Frame::new()
                    .with(pill("sp", 100.0, 60.0, 140.0, 50.0, "stack.pop()", Y, 12.0))
                    .with(tx("sa", 100.0, 96.0, "последним пришёл — первым ушёл", 9.5))
                    .with(pill("qp", 260.0, 60.0, 140.0, 50.0, "queue.popleft()", G, 12.0))
                    .with(tx("qa", 260.0, 96.0, "первым пришёл — первым ушёл", 9.5))
                    .with(mt("sd", 100.0, 130.0, "глубина", 11.0).tone(Y))
                    .with(mt("qd", 260.0, 130.0, "ширина", 11.0).tone(G)),
                _ => f,
            }
        }),
        &[6.1, 12.6, 24.2],
        3000,
    )
}

