    fn steps_labels_captions_and_cues_agree() {
        for (name, spec) in scenes() {
            let n = spec.frames.len();
            assert_eq!(spec.labels.len(), n, "{name}: названия шагов");
            assert_eq!(spec.captions.len(), n, "{name}: подписи");
            let cues = spec.cues.as_ref().unwrap_or_else(|| panic!("{name}: нет меток cues"));
            assert_eq!(cues.len(), n - 1, "{name}: меток шагов");
            assert!(cues.windows(2).all(|w| w[0] < w[1]), "{name}: метки не по возрастанию");
            assert!(spec.height == 170.0, "{name}: высота холста");
        }
    }

    #[test]
    fn no_item_is_visible_but_empty() {
        // у каждой сцены на каждом шаге есть что показать
        for (name, spec) in scenes() {
            let scene = Scene::compile(&spec).unwrap();
            for (k, row) in scene.states.iter().enumerate() {
                assert!(row.iter().any(|i| i.opacity() > 0.0), "{name}: шаг {k} пуст");
            }
        }
    }
