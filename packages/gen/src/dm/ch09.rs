    fn scenes_compile_and_pass_lint() {
        for (name, spec) in scenes() {
            let scene = Scene::compile(&spec).unwrap_or_else(|e| panic!("{name}: {e}"));
            let lint = scene.lint();
            assert!(lint.is_empty(), "{name}: {lint:#?}");
        }
    }

