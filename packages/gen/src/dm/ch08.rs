// --- помощники ----------------------------------------------------------------------------------

/// Вершина: x, y, подпись.
type P = (f64, f64, &'static str);

/// Ребро: от `a` к `b` (индексы вершин), необязательный вес и изгиб дугой.
#[derive(Clone, Copy)]
struct Ed {
    a: usize,
    b: usize,
    w: Option<u32>,
    bend: f64,
}

fn ed(a: usize, b: usize) -> Ed {
    Ed { a, b, w: None, bend: 0.0 }
}

impl Ed {
    fn w(self, w: u32) -> Self {
        Self { w: Some(w), ..self }
    }
    fn bend(self, bend: f64) -> Self {
        Self { bend, ..self }
    }
}

fn eds(pairs: &[(usize, usize)]) -> Vec<Ed> {
    pairs.iter().map(|&(a, b)| ed(a, b)).collect()
}

/// Граф на холсте: узлы `<id>n<i>`, рёбра `<id>e<i>`, веса `<id>w<i>`.
struct Gr {
    id: &'static str,
    nodes: Vec<P>,
    edges: Vec<Ed>,
    directed: bool,
    r: f64,
    lsize: f64,
}

impl Gr {
    fn new(id: &'static str, nodes: &[P], edges: Vec<Ed>) -> Self {
        Self { id, nodes: nodes.to_vec(), edges, directed: false, r: 13.0, lsize: 10.5 }
    }
    fn directed(self) -> Self {
        Self { directed: true, ..self }
    }
    fn r(self, r: f64, lsize: f64) -> Self {
        Self { r, lsize, ..self }
    }
    /// Те же рёбра на других местах (и с другими подписями).
    fn at(&self, nodes: &[P]) -> Self {
        Self { id: self.id, nodes: nodes.to_vec(), edges: self.edges.clone(), directed: self.directed, r: self.r, lsize: self.lsize }
    }
    /// Элементы кадра: рёбра, затем веса, затем узлы (узлы рисуются поверх рёбер). `nc` — цвет узла, `ec` — цвет ребра
    /// (`None` — ребро скрыто), `o` — прозрачность всего графа.
    fn draw(&self, nc: &dyn Fn(usize) -> Tone, ec: &dyn Fn(usize, &Ed) -> Option<Tone>, o: f64) -> Vec<Item> {
        let mut out: Vec<Item> = Vec::new();
        for (i, e) in self.edges.iter().enumerate() {
            let ((ax, ay, _), (bx_, by, _)) = (self.nodes[e.a], self.nodes[e.b]);
            let (dx, dy) = (bx_ - ax, by - ay);
            let d = dx.hypot(dy).max(1e-9);
            let (s, t) = if self.directed { (self.r + 1.0, self.r + 3.0) } else { (0.0, 0.0) };
            let (x1, y1, x2, y2) = (ax + dx / d * s, ay + dy / d * s, bx_ - dx / d * t, by - dy / d * t);
            let tone = ec(i, e);
            let l = if self.directed { arrow(format!("{}e{i}", self.id), x1, y1, x2, y2) } else { line(format!("{}e{i}", self.id), x1, y1, x2, y2) };
            let colored = matches!(tone, Some(c) if c != M);
            out.push(l.tone(tone.unwrap_or(M)).width(if colored { 2.0 } else { 1.4 }).bend(e.bend).opacity(if tone.is_some() { o } else { 0.0 }).into());
        }
        for (i, e) in self.edges.iter().enumerate() {
            if let Some(w) = e.w {
                let ((ax, ay, _), (bx_, by, _)) = (self.nodes[e.a], self.nodes[e.b]);
                out.push(text(format!("{}w{i}", self.id), (ax + bx_) / 2.0, (ay + by) / 2.0 - 4.0, w.to_string()).mono().size(9.5).tone(Y).opacity(o).into());
            }
        }
        for (i, &(x, y, l)) in self.nodes.iter().enumerate() {
            out.push(dot(format!("{}n{i}", self.id), x, y, l).r(self.r).size(self.lsize).tone(nc(i)).opacity(o).into());
        }
        out
    }
    /// Всё приглушённое, полной яркости.
    fn plain(&self) -> Vec<Item> {
        self.draw(&|_| M, &|_, _| Some(M), 1.0)
    }
}

/// Моноширинная подпись по центру: `size` — кегль; цвет — цепочкой `.tone(..)`.
fn mono(id: &str, x: f64, y: f64, s: &str, size: f64) -> Text {
    text(id, x, y, s).mono().size(size)
}

/// Обычная подпись по центру.
fn cap(id: &str, x: f64, y: f64, s: &str, size: f64) -> Text {
    text(id, x, y, s).size(size)
}

/// Пунктирная овальная рамка вокруг группы вершин: прямоугольник (x, y, w, h — левый верхний угол) со скруглением 16.
fn hull(id: &str, x: f64, y: f64, w: f64, h: f64, tone: Tone) -> Path {
    let d = format!(
        "M{} {y} H{} A16 16 0 0 1 {} {} V{} A16 16 0 0 1 {} {} H{} A16 16 0 0 1 {x} {} V{} A16 16 0 0 1 {} {y}Z",
        x + 16.0,
        x + w - 16.0,
        x + w,
        y + 16.0,
        y + h - 16.0,
        x + w - 16.0,
        y + h,
        x + 16.0,
        y + h - 16.0,
        y + 16.0,
        x + 16.0,
    );
    Path { dash: Some("5 4".into()), ..path(id, d).tone(tone).width(1.6) }
}

