/// Все строки таблицы истинности для `n` переменных (1 — истина), в порядке 11, 10, 01, 00.
fn inputs(n: usize) -> Vec<Vec<u8>> {
    (0..1usize << n).map(|i| (0..n).map(|k| ((i >> (n - 1 - k)) & 1) as u8).collect()).collect()
}

