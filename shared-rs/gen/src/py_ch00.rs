#[cfg(test)]
mod tests {
    use super::*;

    /// Глава проходит проверку (все сцены компилируются), у каждого слайда одна схема из трёх шагов с возрастающими метками.
    #[test]
    fn every_scene_compiles_and_matches_its_slide() {
        let ch = chapter();
        ch.check().unwrap();
        assert_eq!(ch.slides.len(), 14);
        for (i, s) in ch.slides.iter().enumerate() {
            let spec = s.scene_spec().unwrap_or_else(|| panic!("слайд {} без сцены", i + 1));
            assert_eq!(spec.frames.len(), 3, "слайд {}", i + 1);
            let cues = spec.cues.as_ref().expect("метки шагов");
            assert_eq!(cues.len(), 2, "слайд {}: меток шагов", i + 1);
            assert!(cues.windows(2).all(|w| w[0] < w[1]), "метки возрастают");
        }
    }
}
