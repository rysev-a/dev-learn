/// Уровни дерева деления: на уровне `l` — `2^l` кусков шириной 320/2^l; верхний край уровня — `y0 + l·dy`.
fn levels(tone: Tone, y0: f64, dy: f64, count: usize) -> Vec<Cell> {
    let mut out = Vec::new();
    for l in 0..count {
        let c = 1usize << l;
        let step = 320.0 / c as f64;
        for j in 0..c {
            out.push(bx(format!("lv{l}_{j}"), 20.0 + j as f64 * step + step / 2.0, y0 + l as f64 * dy + 10.0, step - 4.0, 20.0, "").tone(tone));
        }
    }
    out
}

