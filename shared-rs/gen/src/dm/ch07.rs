fn recap() -> SceneSpec {
    let cards = [("база + шаг", "индукция"), ("P(<k) ⇒ P(k)", "сильная"), ("f(n−1)", "рекурсия"), ("T(n)", "рекуррентности")];
    // шаг `step`: карточка step − 1 подсвечена и увеличена, прежние — пройдены
    let frame = |step: usize| {
        let mut f = Frame::new();
        for (i, (big, name)) in cards.iter().enumerate() {
            let at = i + 1;
            let on = step == at;
            let k = if on { 1.1 } else { 1.0 };
            let cx = 50.0 + i as f64 * 86.0;
            let card = bx(format!("card{i}"), cx, 62.0, 76.0, 80.0, "").tone(if on || step > at { G } else { M });
            f = f
                .with(if on { card.scale(1.1) } else { card })
                .with(mono(&format!("big{i}"), cx, 62.0 + 4.0 * k, big, 11.0 * k).tone(G))
                .with(cap(&format!("name{i}"), cx, 62.0 + 26.0 * k, name, 8.5 * k));
        }
        if step >= 5 {
            f = f.with(pill("next", 180.0, 140.0, 260.0, 26.0, "Глава 8 · графы: основы →", G, 11.0).text_color("var(--s-accent)"));
        }
        f
    };
    spec(
        &["Итог", "Индукция", "Сильная", "Рекурсия", "Рекуррентности", "Дальше"],
        &[
            "Подведём итог главы",
            "Индукция доказывает утверждения для всех натуральных двумя шагами — база и переход: лестница",
            "Сильная индукция разрешает опираться на все предыдущие значения сразу",
            "Рекурсия — это индукция в коде, и её база — вопрос жизни и смерти стека",
            "Рекуррентности записывают алгоритмы формулами и дают время: слияние — n log n, неудачная быстрая — квадрат",
            "Дальше — графы: структуры, где рекурсия и обходы заиграют в полную силу",
        ],
        (0..6).map(frame).collect(),
    )
    .cues(&[1.5, 9.7, 13.6, 18.6, 27.3])
    .step_ms(2600)
}

