#[cfg(test)]
mod tests {
    use super::*;
    use content::Scene;

    const NAMES: [&str; 13] = [
        "C10Intro", "C10Classic", "C10Counting", "C10Events", "C10Independent", "C10Conditional", "C10Bayes", "C10Trap", "C10Spam", "C10BaseRate", "C10Engineering", "C10Diagnostics", "C10Finale",
    ];

    #[test]
    fn names_match_slide_components() {
        let got: Vec<&str> = scenes().iter().map(|(n, _)| *n).collect();
        assert_eq!(got, NAMES);
    }

    #[test]
    fn every_scene_compiles_and_has_clean_layout() {
        for (name, spec) in scenes() {
            let scene = Scene::compile(&spec).unwrap_or_else(|e| panic!("{name}: {e}"));
            let lint = scene.lint();
            assert!(lint.is_empty(), "{name}: {lint:#?}");
        }
    }

    #[test]
    fn steps_labels_captions_and_cues_agree() {
        for (name, spec) in scenes() {
            let n = spec.frames.len();
            assert_eq!(spec.labels.len(), n, "{name}: названия шагов");
            assert_eq!(spec.captions.len(), n, "{name}: подписи");
            let cues = spec.cues.as_ref().unwrap_or_else(|| panic!("{name}: нет меток cues"));
            assert_eq!(cues.len() + 1, n, "{name}: меток шагов");
            assert!(cues.windows(2).all(|w| w[0] < w[1]), "{name}: метки не возрастают");
        }
    }
}
