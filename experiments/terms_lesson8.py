"""Эксперимент: как kokoro-ru озвучивает термины урока 1 книги 8 (Linux).

Три стратегии на одинаковых фразах:
  cur = как сейчас в учебнике (транслит: «иноды», «монтирование», «дэ-эф»)
  lat = англоязычный оригинал латиницей (проверка гипотезы «модель не прочитает»)
  rus = полная русская замена термина
Плюс альтернативные транслитерации и ударения.

Запуск:  uv run python experiments/terms_lesson8.py
Слушать: afplay experiments/01-...wav && ...
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from tts import synthesize_to_wav

OUT = Path(__file__).parent
VOICE = "sveta"

CLIPS: list[tuple[str, str]] = [
    # --- термин «инода / иноды» ---
    ("01-inody-cur", "Имя файла — лишь запись в каталоге, указывающая на номер инода."),
    ("02-inody-lat", "Имя файла — лишь запись в каталоге, указывающая на номер inode."),
    (
        "03-inody-rus",
        "Имя файла — лишь запись в каталоге, указывающая на номер индексного дескриптора.",
    ),
    # --- термин «монтирование» ---
    ("04-mount-cur", "Монтирование — способ врастить новое хранилище в общее дерево."),
    ("05-mount-lat", "Mount — способ врастить новое хранилище в общее дерево."),
    (
        "06-mount-rus",
        "Подключение диска — способ врастить новое хранилище в общее дерево.",
    ),
    # --- команды: как сейчас vs латиница vs альтернативный транслит ---
    ("07-df-cur", "Свободное место и иноды проверьте командой дэ-эф."),
    ("08-df-lat", "Свободное место и inodes проверьте командой df."),
    ("09-df-alt", "Свободное место и иноды проверьте командой ди-эф."),
    # --- путь /etc/hosts ---
    ("10-etc-cur", "Настройки сети лежат в каталоге э-тэ-си-слэш-хостс."),
    ("11-etc-lat", "Настройки сети лежат в каталоге /etc/hosts."),
    ("12-etc-alt", "Настройки сети лежат в каталоге этси хостс."),
    # --- tmpfs ---
    ("13-tmpfs-cur", "Временные файлы живут в тмп-фс и стираются при перезагрузке."),
    ("14-tmpfs-lat", "Временные файлы живут в tmpfs и стираются при перезагрузке."),
    (
        "15-tmpfs-alt",
        "Временные файлы живут в тэ-эм-пэ-эф-эс и стираются при перезагрузке.",
    ),
    # --- ударение: формы слова «инод» ---
    ("16-stress-forms", "Инод, инода, иноду, иноды, инодов, об иноде, в инодах."),
]


def main() -> None:
    OUT.mkdir(exist_ok=True)
    for name, text in CLIPS:
        path = OUT / f"{name}.wav"
        dur = synthesize_to_wav(text, VOICE, path)
        print(f"{name}.wav  {dur:4.1f}s  {text[:60]}")
    print("\nПрослушать попарно:")
    for base in ("inody", "mount", "df", "etc", "tmpfs"):
        nums = [n for n, _ in CLIPS if base in n]
        print("  afplay " + " && afplay ".join(f"experiments/{n}.wav" for n in nums))


if __name__ == "__main__":
    main()
