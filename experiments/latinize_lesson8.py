"""Латинизация путей и команд в уроке 12-linux-01.md (книга 8, глава 1).

Каждая замена проверяется по количеству вхождений — скрипт падает,
если ожидание не совпало. Литеральные \\n\\n не затрагиваются.

Запуск: uv run python experiments/latinize_lesson8.py
"""

from pathlib import Path

F = Path(__file__).parent.parent / "textbook" / "8-linux" / "12-linux-01.md"

# (старое, новое, ожидаемое число замен); порядок важен — сначала длинные
REPLACEMENTS = [
    ("слэш ю-эф-эр слэш бин", "/usr/bin", 1),
    # контент-фикс: флешки живут в /media, а не в /ufr (опечатка в исходнике)
    ("слэш ю-эф-эр — подключаемые флешки", "/media — подключаемые флешки", 1),
    ("слэш ет-си", "/etc", 1),
    ("слэш вар", "/var", 1),
    ("слэш хоум", "/home", 1),
    ("слэш рут", "/root", 1),
    ("слэш темп", "/tmp", 1),
    ("слэш бин", "/bin", 1),
    ("слэш либ", "/lib", 1),
    ("Слэш проц", "/proc", 1),
    ("Слэш сис", "/sys", 1),
    ("Слэш дев", "/dev", 1),
    ("ет-си эф-стаб", "/etc/fstab", 1),
    ("в ет-си, вар лог и проц", "в /etc, /var/log и /proc", 1),
    # итоговый абзац
    (
        "где ет-си — настройки, вар — растущее, а проц, сис и дев — окна",
        "где /etc — настройки, /var — растущее, а /proc, /sys и /dev — окна",
        1,
    ),
    ("а еф-стаб делает это постоянным", "а /etc/fstab делает это постоянным", 1),
    ("командой дэ-ю", "командой du", 1),
    ("командой дэ-эф", "командой df", 1),
]


def main() -> None:
    t = F.read_text()
    for old, new, expected in REPLACEMENTS:
        n = t.count(old)
        if n != expected:
            raise SystemExit(f"ОШИБКА: {old!r} найдено {n} раз, ожидалось {expected}")
        t = t.replace(old, new)
    leftovers = [w for w in ("ет-си", "эф-стаб", "дэ-ю", "дэ-эф", "вар лог") if w in t]
    # «слэш» остаётся дважды: интро и итог («корень называется слэш» / «от корня слэш»)
    n_slash = t.count("слэш")
    if n_slash != 2 or leftovers:
        raise SystemExit(f"ОШИБКА: остатки: слэш={n_slash}, {leftovers}")
    F.write_text(t)
    print(f"OK: {len(REPLACEMENTS)} замен, «слэш» остался только у корня (2 раза)")


if __name__ == "__main__":
    main()
