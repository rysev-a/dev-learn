// 13. Дерево отрезков
const VALS = [5, 3, 7, 1, 4, 6, 2, 8];
const LX = (i: number) => 40 + 40 * i;
const NODE = (lvl: number, i: number) => {
  const span = 2 ** lvl;
  const l = i * span;
  return {
    x: (LX(l) + LX(l + span - 1)) / 2,
    y: 130 - 34 * lvl,
    sum: VALS.slice(l, l + span).reduce((a, b) => a + b, 0),
    l,
    r: l + span - 1,
  };
};
const SEG = (hot: (lvl: number, i: number) => string, vals: number[] = VALS): SceneItem[] => {
  const out: SceneItem[] = [];
  for (let lvl = 0; lvl <= 3; lvl++) {
    for (let i = 0; i < 8 / 2 ** lvl; i++) {
      const nd = NODE(lvl, i);
      const sum = vals.slice(nd.l, nd.r + 1).reduce((a, b) => a + b, 0);
      out.push({
        t: "dot",
        id: `n${lvl}-${i}`,
        x: nd.x,
        y: nd.y,
        r: 11,
        text: sum,
        size: 8.5,
        c: hot(lvl, i),
      });
      if (lvl > 0) {
        for (const ch of [2 * i, 2 * i + 1]) {
          const c = NODE(lvl - 1, ch);
          out.push({
            t: "line",
            id: `ln${lvl}-${i}-${ch}`,
            x1: nd.x + (c.x - nd.x) * 0.25,
            y1: nd.y + 10,
            x2: c.x - (c.x - nd.x) * 0.1,
            y2: c.y - 10,
            c: "m",
            o: 0.6,
          });
        }
      }
    }
  }
  return out;
};
