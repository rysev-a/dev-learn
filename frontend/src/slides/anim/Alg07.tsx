// 9. Схема «разделяй и властвуй»
const DCN = [
  ["r", 180, 28, "n"],
  ["a", 100, 80, "n/2"],
  ["b", 260, 80, "n/2"],
  ["c", 60, 134, "n/4"],
  ["d", 140, 134, "n/4"],
  ["e", 220, 134, "n/4"],
  ["f", 300, 134, "n/4"],
] as const;
const DCE: [string, string][] = [
  ["r", "a"],
  ["r", "b"],
  ["a", "c"],
  ["a", "d"],
  ["b", "e"],
  ["b", "f"],
];
const DCSC = (k: number): SceneItem[] => {
  const pos = Object.fromEntries(DCN.map(([id, x, y]) => [id, { x, y }]));
  return [
    ...DCE.map(([a, b]) =>
      edge(`${a}${b}`, pos[a], pos[b], {
        r: 12,
        c: k >= 1 ? "g" : "m",
        arrow: true,
        o: k >= 1 ? 1 : 0,
      }),
    ),
    ...DCN.map(([id, x, y, t]): SceneItem => ({
      t: "dot",
      id,
      x,
      y,
      r: 13,
      text: t,
      size: 8.5,
      c:
        k === 0
          ? id === "r"
            ? "y"
            : "m"
          : k === 1
            ? id === "r"
              ? "m"
              : "y"
            : k === 2
              ? y > 100
                ? "g"
                : "m"
              : "g",
      o: k === 0 && id !== "r" ? 0 : 1,
    })),
  ];
};
