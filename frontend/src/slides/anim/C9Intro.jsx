import { G, GraphView, Pill, Steps, Txt, useSteps } from "./kit.tsx";

/* Глава 9, слайд 1: обходы вокруг нас — сборщик мусора, краулер,
   менеджер пакетов; что такое обход. */

const LABELS = ["Глава", "Невидимые обходы", "Что такое", "План", "Продакшн"];
const CAPTION = [
  "Обходы графов и деревья",
  "Пока вы спите, сборщик мусора, краулер и менеджер пакетов обходят свои графы",
  "Обход — побывать во всех вершинах, не заблудившись и не зациклившись",
  "Сегодня: два способа обхода, деревья и кёнигсбергские мосты",
  "Всё это вы встретите в продакшне — уже узнав в лицо",
];
const MINI = (dx) => ({
  nodes: [
    { x: dx, y: 50, l: "" },
    { x: dx - 26, y: 100, l: "" },
    { x: dx + 26, y: 100, l: "" },
  ],
  edges: [
    { a: 0, b: 1 },
    { a: 0, b: 2 },
    { a: 1, b: 2 },
  ],
});
const N = [
  { x: 90, y: 40, l: "S" },
  { x: 180, y: 40, l: "2" },
  { x: 270, y: 40, l: "3" },
  { x: 130, y: 110, l: "4" },
  { x: 230, y: 110, l: "5" },
];
const E = [
  { a: 0, b: 1 },
  { a: 1, b: 2 },
  { a: 0, b: 3 },
  { a: 3, b: 4 },
  { a: 4, b: 2 },
];

export default function C9Intro({ cues }) {
  const ctl = useSteps(cues || [4.5, 15.8, 24.1, 29.7], 2800);
  const { step } = ctl;
  return (
    <Steps ctl={ctl} labels={LABELS} caption={CAPTION}>
      <Txt x="180" y="80" mono size={22} o={step === 0 ? 1 : 0} color="var(--s-accent)">обход графа</Txt>
      <G o={step === 1 ? 1 : 0}>
        {[
          ["сборщик мусора", 70],
          ["краулер", 180],
          ["менеджер пакетов", 290],
        ].map(([t, x], i) => (
          <g key={t}>
            <GraphView {...MINI(x)} r={9} nc={() => ["g", "b", "y"][i]} ec={() => ["g", "b", "y"][i]} />
            <Txt x={x} y="136" size={9.5}>{t}</Txt>
          </g>
        ))}
      </G>
      <GraphView nodes={N} edges={E} nc={() => "g"} ec={() => "g"} o={step === 2 ? 1 : 0} />
      <Txt x="180" y="152" mono size={11} o={step === 2 ? 1 : 0} color="var(--s-accent)">каждая вершина — один раз, без зацикливания</Txt>
      <G o={step === 3 ? 1 : 0}>
        {["2 способа обхода", "деревья", "кёнигсбергские мосты"].map((t, i) => (
          <Pill key={t} x={180} y={34 + i * 38} w={230} h={28} text={t} stroke="var(--s-accent)" size={11} />
        ))}
      </G>
      <Txt x="180" y="86" mono size={16} o={step >= 4 ? 1 : 0} color="var(--s-accent)">узнать в лицо — до продакшна</Txt>
    </Steps>
  );
}
