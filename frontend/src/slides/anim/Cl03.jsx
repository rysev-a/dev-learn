const strip = (prefix, x0, y, vals, c = "b", w = 38, hl = []) =>
  vals.map((v, i) =>
    Box(
      `${prefix}${i}`,
      x0 + i * (w + 2),
      y,
      w,
      26,
      `${v}`,
      hl.includes(i) ? "y" : c,
      { size: 9.5 },
    ),
  );
const addrs = (prefix, x0, y, start, step, n, w = 38) =>
  Array.from({ length: n }, (_, i) =>
    Tx(
      `${prefix}${i}`,
      x0 + i * (w + 2),
      y,
      `${(start + i * step).toString(16)}`,
      { size: 7.5, mono: true },
    ),
  );

