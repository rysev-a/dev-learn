// таблица ячеек: vals — двумерный массив; reveal(r, c) — показывать ли; hot(r, c) — цвет
function TBL(
  id,
  vals,
  {
    x0 = 120,
    y0 = 40,
    cw = 36,
    ch = 24,
    reveal = () => true,
    hot = () => null,
    rows = null,
    cols = null,
    size = 10,
  } = {},
) {
  const out = [];
  if (cols)
    cols.forEach((l, c) =>
      out.push(
        Tx(`${id}c${c}`, x0 + cw * c, y0 - 20, l, { mono: true, size: 8.5 }),
      ),
    );
  if (rows)
    rows.forEach((l, r) =>
      out.push(
        Tx(`${id}r${r}`, x0 - cw * 0.75, y0 + ch * r + 3, l, {
          mono: true,
          size: 8.5,
          anchor: "end",
        }),
      ),
    );
  vals.forEach((rw, r) =>
    rw.forEach((v, c) =>
      out.push({
        t: "cell",
        id: `${id}${r}-${c}`,
        x: x0 + cw * c,
        y: y0 + ch * r,
        w: cw - 4,
        h: ch - 4,
        text: v,
        size,
        c: hot(r, c) ?? (reveal(r, c) ? "b" : "n"),
        o: reveal(r, c) ? 1 : 0.2,
      }),
    ),
  );
  return out;
}

