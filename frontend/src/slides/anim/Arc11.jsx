// 4. Арифметика, инкремент и декремент
const arith = (a, b, kind) => {
  const ops = {
    add: [a + b, "+", "A + B"],
    sub: [a - b, "−", "A − B = A + не B + 1"],
    inc: [a + 1, "+", "A + 1"],
    dec: [a - 1, "−", "A − 1"],
  };
  const [raw, sign] = ops[kind];
  const r = ((raw % 4) + 4) % 4;
  const co =
    kind === "sub"
      ? a >= b
        ? 1
        : 0
      : kind === "dec"
        ? a >= 1
          ? 1
          : 0
        : raw > 3
          ? 1
          : 0;
  const bb = kind === "inc" || kind === "dec" ? 1 : b;
  return [
    ...bin(a)
      .split("")
      .map((x, i) =>
        Box(`a${i}`, 70 + i * 24, 60, 20, 22, x, "m", { size: 11 }),
      ),
    Tx("sg", 130, 60, sign, { size: 13, mono: true }),
    ...bin(bb)
      .split("")
      .map((x, i) =>
        Box(`b${i}`, 180 + i * 24, 60, 20, 22, x, "m", { size: 11 }),
      ),
    Tx("eq", 235, 60, "=", { size: 13, mono: true }),
    ...bin(r)
      .split("")
      .map((x, i) =>
        Box(`r${i}`, 270 + i * 24, 60, 20, 22, x, "g", { size: 11 }),
      ),
    Box("co", 290, 110, 90, 24, `Co = ${co}`, co ? "y" : "m", { size: 10 }),
    Tx("f", 120, 110, ops[kind][2], { size: 10, mono: true }),
    Tx(
      "n",
      180,
      150,
      kind === "sub"
        ? "Co = 1: заёма не было, A ≥ B"
        : kind === "add"
          ? "результат по модулю 4"
          : "по кругу: 11 → 00 и 00 → 11",
      { size: 9.5 },
    ),
  ];
};
