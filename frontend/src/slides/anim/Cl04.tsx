const chars = (prefix: string, x0: number, y: number, s: string, w = 30, c = "b", hl: number[] = []) =>
  [...s].map((ch, i) =>
    Box(
      `${prefix}${i}`,
      x0 + i * (w + 2),
      y,
      w,
      26,
      ch === "\0" ? "\\0" : ch,
      ch === "\0" ? "r" : hl.includes(i) ? "y" : c,
      { size: 10 },
    ),
  );

