// 6. Ячейка с защитой записи
const cellp = (w: number, wp: number, rd: number, d: number, q: number) => {
  const en = w & (1 - wp);
  const qn = en ? d : q;
  return [
    bit("d", 24, 36, d),
    bit("w", 24, 70, w),
    bit("wp", 24, 104, wp, { c: wp ? "r" : "m" }),
    bit("rd", 24, 138, rd),
    Tx("dl", 46, 36, "D", { size: 8.5, anchor: "start" }),
    Tx("wl", 46, 70, "W", { size: 8.5, anchor: "start" }),
    Tx("wpl", 46, 104, "WP (защита)", { size: 8.5, anchor: "start" }),
    Tx("rl", 46, 138, "RD", { size: 8.5, anchor: "start" }),
    GT("n", "not", 120, 104, { s: 0.8, c: "r" }),
    GT("a", "and", 190, 76, { s: 1, c: "b" }),
    Box("l", 260, 60, 60, 48, `защёлка\n${qn}`, qn ? "g" : "m", { size: 9 }),
    pl(
      "o",
      [
        [212, 76],
        [225, 76],
        [225, 60],
        [230, 60],
      ],
      lv(en),
    ),
    GT("r", "and", 260, 130, { s: 1, c: "b" }),
    pl(
      "q",
      [
        [260, 84],
        [260, 118],
        [238, 118],
      ],
      lv(qn),
    ),
    pl(
      "rr",
      [
        [36, 138],
        [238, 138],
      ],
      lv(rd),
    ),
    pl(
      "out",
      [
        [282, 130],
        [320, 130],
      ],
      lv(rd & qn),
    ),
    bit("out", 336, 130, rd & qn),
    Tx("ol", 336, 114, "Out", { size: 8.5 }),
    Tx(
      "n",
      190,
      36,
      en
        ? "запись разрешена"
        : w
          ? "запись заблокирована защитой"
          : "записи нет",
      { size: 9, c: en ? "g" : w ? "r" : undefined },
    ),
  ];
};
