// 2. ПЗУ как матрица
const ROM4: [number, number][] = [
  [1, 0],
  [0, 1],
  [1, 1],
  [0, 0],
];
const rom = (addr: number) => {
  const items = [
    Tx("hd", 120, 14, "строки ← дешифратор", { size: 8.5 }),
    Tx("hd2", 290, 14, "линии данных", { size: 8.5 }),
  ];
  ROM4.forEach((w, i) => {
    items.push(
      pl(
        `row${i}`,
        [
          [40, 38 + i * 30],
          [320, 38 + i * 30],
        ],
        i === addr ? "g" : "m",
        { w: 1.8 },
      ),
    );
    items.push(Tx(`rl${i}`, 24, 38 + i * 30, `${i}`, { size: 9, mono: true }));
    w.forEach((b, k) => {
      if (b)
        items.push({
          t: "dot",
          id: `d${i}${k}`,
          x: 240 + k * 50,
          y: 38 + i * 30,
          r: 4.5,
          text: "",
          c: i === addr ? "g" : "b",
        });
    });
  });
  [0, 1].forEach((k) =>
    items.push(
      pl(
        `col${k}`,
        [
          [240 + k * 50, 24],
          [240 + k * 50, 150],
        ],
        ROM4[addr][k] ? "g" : "m",
        { w: 2 },
      ),
      bit(`o${k}`, 240 + k * 50, 162, ROM4[addr][k], {
        w: 22,
        h: 18,
        size: 10,
      }),
      Tx(`ol${k}`, 266 + k * 50, 162, k ? "D0" : "D1", {
        size: 8,
        anchor: "start",
      }),
    ),
  );
  return items;
};
