// сегменты горизонтальной полосы: [[id, ширина, текст, цвет], …] начиная с x0
const seg = (x0: number, y: number, h: number, parts: readonly (readonly [string, number, string, string])[]): SceneItem[] => {
  let x = x0;
  return parts.map(([id, w, text, c]) => {
    const it = Bx(id, x + w / 2, y, Math.max(w - 2, 1), h, w > 18 ? text : "", c, { size: 8.5 });
    x += w;
    return it;
  });
};

