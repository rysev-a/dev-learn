// слот полного дерева с индексом i
const SLOT = (i, { y0 = 24, dy = 32, W = 300 } = {}) => {
  const lvl = Math.floor(Math.log2(i + 1));
  const j = i - (2 ** lvl - 1);
  return {
    x: 180 + (j + 0.5 - 2 ** lvl / 2) * (W / 2 ** lvl),
    y: y0 + lvl * dy,
  };
};
const ACOL = (x0, cw, i) => x0 + cw * i;

// куча: дерево по слотам (узлы-значения переезжают между слотами) + массив-лента
function HEAP(
  arr,
  colors = {},
  { dy = 32, W = 300, y0 = 24, arrY = 148, showArr = true } = {},
) {
  const items = [];
  const n = arr.length;
  for (let i = 1; i < n; i++) {
    const p = Math.floor((i - 1) / 2);
    items.push(
      edge(`e${i}`, SLOT(p, { y0, dy, W }), SLOT(i, { y0, dy, W }), {
        r: 11,
        c: colors[`~${i}`] ?? "m",
      }),
    );
  }
  arr.forEach((v, i) => {
    const s = SLOT(i, { y0, dy, W });
    items.push({
      t: "dot",
      id: `v${v}`,
      x: s.x,
      y: s.y,
      r: 11,
      text: v,
      size: 10,
      c: colors[v] ?? "m",
    });
    if (showArr)
      items.push({
        t: "cell",
        id: `a${v}`,
        x: ACOL(64, 34, i),
        y: arrY,
        w: 30,
        h: 22,
        text: v,
        size: 10,
        c: colors[v] ?? "m",
        sub: i,
        subSize: 7.5,
      });
  });
  return items;
}

