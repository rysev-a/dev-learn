// 4. Spinlock
const spn = (n: number): SceneItem[] => {
  const holder = n >= 3 ? "B" : n >= 1 ? "A" : null;
  const cell = (k: string|null, x: number) =>
    Bx(
      `c${k}`,
      x,
      112,
      76,
      30,
      k === "A" ? "ядро A" : k === "B" ? "ядро B" : "ядро C",
      holder === k
        ? "g"
        : (n === 2 || n === 3) && k !== holder && !(n === 3 && k === "A")
          ? "y"
          : "m",
      { size: 9.5 },
    );
  return [
    Bx(
      "lock",
      180,
      40,
      120,
      28,
      n === 0
        ? "спинлок: свободен"
        : n === 3
          ? "спинлок → ядро B"
          : "спинлок: занят A",
      n === 0 ? "g" : "r",
      { size: 9.5 },
    ),
    cell("A", 60),
    cell("B", 180),
    cell("C", 300),
    ...If(n >= 1 && n <= 2, Ar("t", 70, 96, 150, 58, "g")),
    ...If(n === 3, Ar("t2", 180, 96, 180, 58, "g")),
    ...If(
      n === 2,
      Tx("sp", 240, 142, "крутятся в цикле:\nпроверяют флаг", {
        size: 8.5,
        c: "y",
      }),
    ),
    ...If(
      n === 1,
      Tx("pre", 90, 144, "вытеснение запрещено", { size: 8.5, c: "g" }),
    ),
    ...If(
      n === 3,
      Tx("q", 240, 144, "очередь: B вошёл, C ждёт", { size: 8.5, c: "g" }),
    ),
  ];
};
