const py = (id, x, y, lines, hl, extra = {}) =>
  cc(id, x, y, lines, hl, { lang: "py", ...extra });
const bits = (prefix, x0, y, str, c = "b", w = 14) =>
  [...str].map((ch, i) =>
    Box(`${prefix}${i}`, x0 + i * (w + 1), y, w, 18, ch, c, { size: 8.5 }),
  );

