const grid = (pre, names, x0, y0, dx, dy, cols, w, h, color, extra = {}) =>
  names.map((n, i) =>
    Box(
      `${pre}${i}`,
      x0 + (i % cols) * dx,
      y0 + Math.floor(i / cols) * dy,
      w,
      h,
      n,
      typeof color === "function" ? color(i) : color,
      extra,
    ),
  );

