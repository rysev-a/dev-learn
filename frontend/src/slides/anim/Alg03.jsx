const Lk = (id, a, b, { c = "g", o = 1, down = false, bend, dash } = {}) =>
  down
    ? {
        t: "line",
        id,
        x1: a.x,
        y1: a.y + 13,
        x2: b.x,
        y2: b.y - 15,
        c,
        arrow: true,
        o,
        bend,
        dash,
      }
    : {
        t: "line",
        id,
        x1: a.x + 15,
        y1: a.y,
        x2: b.x - 24,
        y2: b.y,
        c,
        arrow: true,
        o,
        bend,
        dash,
      };
const P = (id, x, y, text, c = "g", dir = "down") => ({
  t: "ptr",
  id,
  x,
  y,
  text,
  c,
  dir,
});

