// 8. Слияние двух отсортированных списков (значения переезжают в результат)
const SLOT = (k) => 46 + 54 * k;
const V = (v, x, y, c = "m") => ({
  t: "cell",
  id: `v${v}`,
  x,
  y,
  w: 38,
  h: 24,
  text: v,
  c,
});
const AR = [
  [1, 60, 30],
  [4, 130, 30],
  [7, 200, 30],
];
const BR = [
  [2, 60, 68],
  [3, 130, 68],
  [8, 200, 68],
];
const mergeFrame = (moved, pa, pb, note) => {
  const order = [1, 2, 3, 4, 7, 8];
  const items = [];
  [...AR, ...BR].forEach(([v, x, y]) => {
    const k = order.indexOf(v);
    items.push(
      moved.includes(v)
        ? V(v, SLOT(k), 124, "g")
        : V(v, x, y, v === pa || v === pb ? "y" : "m"),
    );
  });
  if (pa)
    items.push({
      t: "ptr",
      id: "pa",
      x: AR.find((a) => a[0] === pa)[1],
      y: 14,
      text: "a",
      c: "y",
    });
  if (pb)
    items.push({
      t: "ptr",
      id: "pb",
      x: BR.find((b) => b[0] === pb)[1],
      y: 84,
      text: "b",
      c: "b",
      dir: "up",
    });
  items.push({
    t: "text",
    id: "nt",
    x: 290,
    y: 52,
    text: note,
    mono: true,
    size: 9.5,
  });
  return items;
};
