/* Глава 5 книги «Системный дизайн»: шардирование. */

const SH = (n: number, c = "y", y = 80, hs?: number[]) =>
  Array.from({ length: n }, (_, i) => X(`s${i}`, 180 + (i - (n - 1) / 2) * (300 / n), y, hs ? `шард ${i + 1}\n${hs[i]}%` : `шард ${i + 1}`, hs ? (hs[i] ?? 0) > 80 ? "r" : "g" : c, Math.min(64, 280 / n - 6), 34));

