/* Глава 22 книги «Базы данных»: репликация. */

const node = (id: string, x: number, y: number, text: string, c = "b", w = 74) =>
  Box(id, x, y, w, 30, text, c, { size: 9 });
const logrow = (prefix: string, x0: number, y: number, vals: (string | number)[], hot: number[] = [], c = "y") =>
  vals.map((v, i: number) =>
    Box(
      `${prefix}${i}`,
      x0 + i * 30,
      y,
      26,
      20,
      String(v),
      hot.includes(i) ? "g" : c,
      { size: 8.5 },
    ),
  );

