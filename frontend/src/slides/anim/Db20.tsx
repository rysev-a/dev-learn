const pg = (prefix: string, x0: number, y: number, n: number, c = "b", w = 36, hot: number[] = [], dirty: number[] = []) =>
  Array.from({ length: n }, (_, i) =>
    Box(
      `${prefix}${i}`,
      x0 + i * (w + 4),
      y,
      w,
      28,
      `p${i + 1}`,
      dirty.includes(i) ? "y" : hot.includes(i) ? "g" : c,
      { size: 9 },
    ),
  );

