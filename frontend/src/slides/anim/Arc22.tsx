// 7. Гонка данных
const race = (n: number) => {
  const rows: [string, string][] = [
    ["поток 1: читает 0", "m"],
    ["поток 2: читает 0", "m"],
    ["поток 1: пишет 1", "g"],
    ["поток 2: пишет 1", "r"],
  ];
  return [
    ...rows.map(([t, c], i) =>
      Box(`r${i}`, 130, 30 + i * 28, 210, 22, t, i < n ? c : "m", {
        size: 9.5,
        o: i < n ? 1 : 0.35,
      }),
    ),
    Box(
      "v",
      300,
      70,
      100,
      30,
      n >= 4 ? "счётчик = 1 (!)" : n >= 3 ? "счётчик = 1" : "счётчик = 0",
      n >= 4 ? "r" : "y",
      { size: 9.5 },
    ),
    ...(n >= 4
      ? [
          Tx("n", 190, 150, "два прибавления — результат 1: одно потеряно", {
            size: 9.5,
            c: "r",
          }),
        ]
      : []),
  ];
};
