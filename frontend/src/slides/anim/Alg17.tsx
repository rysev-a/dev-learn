// 10. Отсечения: ферзи
const NQ = 4;
const attacked = (queens: XY[]) => {
  const s = new Set<number>();
  for (let r = 0; r < NQ; r++)
    for (let c = 0; c < NQ; c++)
      for (const [qr, qc] of queens)
        if (r !== qr || c !== qc) {
          if (c === qc || r === qr || Math.abs(r - qr) === Math.abs(c - qc))
            s.add(r * NQ + c);
        }
  return s;
};
const board = (queens: XY[], dead: boolean, note: string): SceneItem[] => {
  const att = attacked(queens);
  const out: SceneItem[] = [];
  for (let r = 0; r < NQ; r++)
    for (let c = 0; c < NQ; c++) {
      const isQ = queens.some(([qr, qc]) => qr === r && qc === c);
      out.push({
        t: "cell",
        id: `q${r}${c}`,
        x: 100 + 40 * c,
        y: 40 + 34 * r,
        w: 36,
        h: 30,
        text: isQ ? "Q" : "",
        c: isQ ? "g" : dead && r === 2 ? "r" : att.has(r * NQ + c) ? "W" : "m",
        size: 13,
        o: att.has(r * NQ + c) && !isQ ? 0.6 : 1,
      });
    }
  out.push(
    Tx("n", 180, 176, note, { mono: true, size: 10, c: dead ? "r" : "y" }),
  );
  return out;
};
