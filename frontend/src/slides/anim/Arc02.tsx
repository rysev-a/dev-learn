// 2. Кремний и примеси
const COLS = 5;
const ROWS = 3;
const atomXY = (i: number) => ({
  x: 56 + (i % COLS) * 62,
  y: 34 + Math.floor(i / COLS) * 46,
});
const lattice = (kind: string): SceneItem[] => {
  const items: SceneItem[] = [];
  for (let r = 0; r < ROWS; r++)
    for (let c = 0; c < COLS; c++) {
      if (c < COLS - 1)
        items.push({
          t: "line",
          id: `bh${r}${c}`,
          x1: 56 + c * 62 + 11,
          y1: 34 + r * 46,
          x2: 56 + (c + 1) * 62 - 11,
          y2: 34 + r * 46,
          c: "m",
          w: 1.3,
        });
      if (r < ROWS - 1)
        items.push({
          t: "line",
          id: `bv${r}${c}`,
          x1: 56 + c * 62,
          y1: 34 + r * 46 + 11,
          x2: 56 + c * 62,
          y2: 34 + (r + 1) * 46 - 11,
          c: "m",
          w: 1.3,
        });
    }
  for (let i = 0; i < COLS * ROWS; i++) {
    const { x, y } = atomXY(i);
    const mid = i === 7;
    items.push({
      t: "dot",
      id: `a${i}`,
      x,
      y,
      r: 11,
      text: mid ? (kind === "n" ? "As" : kind === "p" ? "B" : "Si") : "Si",
      c: mid && kind === "n" ? "y" : mid && kind === "p" ? "r" : "m",
      size: 8.5,
    });
  }
  const m = atomXY(7);
  items.push({
    t: "dot",
    id: "ele",
    x: m.x + 28,
    y: m.y - 26,
    r: 3.5,
    text: "",
    c: "b",
    o: kind === "n" ? 1 : 0,
  });
  items.push({
    t: "dot",
    id: "hole",
    x: m.x - 31,
    y: m.y,
    r: 4,
    text: "",
    c: "r",
    o: kind === "p" ? 1 : 0,
    s: 1,
  });
  items.push(
    Tx(
      "lab",
      180,
      150,
      kind === "n"
        ? "лишний электрон свободно движется"
        : kind === "p"
          ? "дырка перемещается как положительный заряд"
          : "все электроны заняты в связях",
      { size: 9.5, c: kind ? "g" : undefined },
    ),
  );
  return items;
};
