const nd = (id, x, y, text, c = "b", w = 66) =>
  Box(id, x, y, w, 28, text, c, { size: 9 });
const sm = (id, x, y, text, c = "b", w = 40) =>
  Box(id, x, y, w, 20, text, c, { size: 8 });
const dots = (prefix, x0, y, n, c = "b", gap = 22) =>
  Array.from({ length: n }, (_, i) => ({
    t: "dot",
    id: `${prefix}${i}`,
    x: x0 + i * gap,
    y,
    r: 5,
    text: "",
    c,
  }));

