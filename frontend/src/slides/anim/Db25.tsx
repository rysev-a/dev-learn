/* Глава 25 книги «Базы данных»: кэш. */

const slots = (prefix: string, x0: number, y: number, vals: (string | number)[], hot: number[] = [], dim: number[] = []) =>
  vals.map((v, i: number) =>
    Box(
      `${prefix}${i}`,
      x0 + i * 46,
      y,
      42,
      24,
      String(v),
      hot.includes(i) ? "g" : "b",
      { size: 9, o: dim.includes(i) ? 0.3 : 1 },
    ),
  );

