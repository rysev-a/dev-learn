// Дерево отрезков для 8 листьев
const SL = [5, 3, 7, 1, 4, 2, 6, 8];
const SX = (id: number) => {
  // id в куче: 1 — корень, 8…15 — листья
  const d = Math.floor(Math.log2(id));
  const pos = id - (1 << d);
  const w = 8 / (1 << d);
  return { x: 40 + 40 * (pos * w + (w - 1) / 2), y: 44 + 32 * d };
};
const SV = (() => {
  const v = Array(16).fill(0);
  for (let i = 0; i < 8; i++) v[8 + i] = SL[i];
  for (let i = 7; i >= 1; i--) v[i] = v[2 * i] + v[2 * i + 1];
  return v;
})();
const seg = (
  show: number[],
  col: Record<string | number, string> = {},
  vals: Record<number, string | number> = {},
  tags: Record<string, string> = {},
  note = "",
): SceneItem[] => {
  const items: SceneItem[] = [];
  for (let id = 2; id < 16; id++) {
    if (
      show.includes(Math.floor(Math.log2(id))) &&
      show.includes(Math.floor(Math.log2(id)) - 1)
    ) {
      const p = SX(id >> 1);
      const q = SX(id);
      items.push(
        edge(`e${id}`, p, q, { r: 11, c: "m", o: col[id] === "n" ? 0.35 : 1 }),
      );
    }
  }
  for (let id = 1; id < 16; id++) {
    const d = Math.floor(Math.log2(id));
    if (!show.includes(d)) continue;
    const { x, y } = SX(id);
    items.push({
      t: "cell",
      id: `s${id}`,
      x,
      y,
      w: d === 3 ? 34 : 38,
      h: 22,
      text: vals[id] ?? SV[id],
      c: col[id] ?? "m",
      o: col[id] === "n" ? 0.4 : 1,
      size: 10.5,
    });
  }
  for (const [id, t] of Object.entries(tags)) {
    const { x, y } = SX(Number(id));
    items.push(Tx(`tag${id}`, x, y - 17, t, { mono: true, size: 8.5, c: "b" }));
  }
  if (note)
    items.push(Tx("n", 180, 166, note, { mono: true, size: 10, c: "y" }));
  return items;
};
