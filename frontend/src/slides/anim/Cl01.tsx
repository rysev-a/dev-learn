const bits = (prefix: string, x0: number, y: number, str: string, c = "b", w = 28, hl: number[] = []) =>
  [...str].map((ch, i) =>
    Box(
      `${prefix}${i}`,
      x0 + i * (w + 2),
      y,
      w,
      24,
      ch,
      hl.includes(i) ? "y" : c,
      { size: 10 },
    ),
  );

