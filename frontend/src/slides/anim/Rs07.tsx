const cells = (
  pre: string,
  vals: (string | number)[],
  c = "b",
  y = 66,
  x0 = 40,
  step = 56,
  w = 48,
  size = 12,
) =>
  vals.map((v, i: number) =>
    Box(`${pre}${i}`, x0 + i * step, y, w, 32, String(v), c, { size }),
  );

