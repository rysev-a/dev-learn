const keys = (prefix: string, x0: number, y: number, vals: (string | number)[], c = "b", w = 26, hot: number[] = []) =>
  vals.map((v, i: number) =>
    Box(
      `${prefix}${i}`,
      x0 + i * (w + 2),
      y,
      w,
      22,
      String(v),
      hot.includes(i) ? "g" : c,
      { size: 8.5 },
    ),
  );

