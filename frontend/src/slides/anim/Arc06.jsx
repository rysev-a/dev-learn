// 2. Таблица истинности удваивается
const tbl = (n) => {
  const rows = 1 << n;
  const w = Math.min(34, 300 / rows);
  const x0 = 180 - (w * (rows - 1)) / 2;
  const out = [];
  for (let i = 0; i < rows; i++) {
    out.push({
      t: "cell",
      id: `c${i}`,
      x: x0 + w * i,
      y: 84,
      w: w - 3,
      h: 24,
      text: i.toString(2).padStart(n, "0"),
      c: "b",
      size: rows > 4 ? 8.5 : 10.5,
    });
  }
  return out;
};
