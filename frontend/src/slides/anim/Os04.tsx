// 6. Дерево и усыновление
const NODES: Record<string, [number, number, string]> = {
  init: [200, 18, "systemd 1"],
  sshd: [110, 56, "sshd 800"],
  cron: [290, 56, "cron 900"],
  bash: [110, 96, "bash 1200"],
  c1: [60, 138, "sleep 1201"],
  c2: [160, 138, "grep 1202"],
};
const tt = (n: number): SceneItem[] => {
  const P = (k: string) => ({ x: NODES[k][0], y: NODES[k][1] });
  const node = (k: string, c?: string, extra: Extra = {}) =>
    Bx(k, NODES[k][0], NODES[k][1], 76, 22, NODES[k][2], c, {
      size: 8.5,
      ...extra,
    });
  const link = (id: string, a: string, b: string, c = "m", extra: Extra = {}) =>
    Ln(id, P(a).x, P(a).y + 11, P(b).x, P(b).y - 11, c, extra);
  return [
    node("init", "g"),
    node("sshd", "m"),
    node("cron", "m"),
    node("bash", n === 1 ? "r" : "m", { o: n >= 2 ? 0 : 1, dash: n === 1 }),
    node("c1", n >= 2 ? "y" : "m"),
    node("c2", n >= 2 ? "y" : "m"),
    link("l1", "init", "sshd"),
    link("l2", "init", "cron"),
    link("l3", "sshd", "bash", "m", { o: n >= 2 ? 0 : 1 }),
    link("l4", "bash", "c1", "m", { o: n >= 2 ? 0 : 1 }),
    link("l5", "bash", "c2", "m", { o: n >= 2 ? 0 : 1 }),
    Pl(
      "n1",
      [
        [160, 18],
        [10, 18],
        [10, 138],
        [22, 138],
      ],
      "y",
      { o: n >= 2 ? 1 : 0 },
    ),
    Ln("n2", 200, 29, 160, 127, "y", { o: n >= 2 ? 1 : 0, bend: -14 }),
    ...If(n === 1, Tx("x", 235, 96, "родитель умер", { size: 9, c: "r" })),
    ...If(
      n >= 2,
      Tx(
        "y",
        270,
        118,
        n === 2 ? "усыновлены\nпроцессом 1" : "pstree: дети\nпод процессом 1",
        { size: 9, c: "y" },
      ),
    ),
  ];
};
