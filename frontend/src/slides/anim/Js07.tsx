/* Глава 7 книги «Современный Frontend»: объекты, массивы и коллекции. */

const cells = (prefix: string, x0: number, y: number, vals: (string | number)[], c: string | ((i: number) => string) = "b", w = 44, extra: Extra = {}): SceneItem[] =>
  vals.map((v, i: number) =>
    Box(
      `${prefix}${i}`,
      x0 + i * (w + 4),
      y,
      w,
      26,
      String(v),
      typeof c === "function" ? c(i) : c,
      { size: 10.5, ...extra },
    ),
  );

