// 5. FizzBuzz
const FB = Array.from({ length: 15 }, (_, i) => {
  const n = i + 1;
  return n % 15 === 0
    ? "FizzBuzz"
    : n % 3 === 0
      ? "Fizz"
      : n % 5 === 0
        ? "Buzz"
        : String(n);
});
const fb = (hl) => [
  ...FB.map((t, i) =>
    Box(
      `f${i}`,
      40 + (i % 5) * 70,
      36 + Math.floor(i / 5) * 36,
      62,
      26,
      t,
      i === hl
        ? "g"
        : t === "FizzBuzz"
          ? "y"
          : t === "Fizz"
            ? "b"
            : t === "Buzz"
              ? "r"
              : "m",
      { size: t.length > 4 ? 8 : 10 },
    ),
  ),
  Tx(
    "n",
    190,
    152,
    hl < 0 ? "" : `число ${hl + 1}: rem 15, rem 3, rem 5 → ${FB[hl]}`,
    { size: 9, mono: true },
  ),
];
