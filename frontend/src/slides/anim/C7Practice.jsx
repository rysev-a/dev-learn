import { Arrow, Dot, G, Pill, Steps, Txt, useSteps } from "./kit.tsx";

/* Глава 7, слайд 12: практические выводы — база и приближение к ней,
   что остаётся верным на каждом шаге, рекуррентность для времени. */

const LABELS = ["Выводы", "Рекурсия", "Доказательство", "Время", "Три вопроса"];
const CAPTION = [
  "Несколько практических выводов в копилку",
  "Пишете рекурсию — сначала сформулируйте базу и убедитесь, что каждый вызов двигается к ней",
  "Доказываете алгоритм — ищите утверждение, верное на каждом шаге: гипотеза индукции или инвариант",
  "Оцениваете время — записывайте рекуррентность: сколько стоит уровень и сколько уровней",
  "Три наводящих вопроса превращают «кажется, работает» в «работает, и вот почему»",
];

export default function C7Practice({ cues }) {
  const ctl = useSteps(cues || [2.8, 10.2, 18.8, 24.8], 3000);
  const { step } = ctl;
  return (
    <Steps ctl={ctl} labels={LABELS} caption={CAPTION}>
      <Txt x="180" y="86" mono size={22} o={step === 0 ? 1 : 0} color="var(--s-accent)">база · шаг · время</Txt>
      <G o={step === 1 ? 1 : 0}>
        {[5, 4, 3, 2, 1, 0].map((v, i) => (
          <g key={v}>
            <Dot x={40 + i * 56} y={64} r={16} text={v} stroke={v === 0 ? "var(--s-accent)" : "var(--s-blue)"} fill={v === 0 ? "var(--s-green)" : "var(--s-panel2)"} size={12} />
            {i < 5 && <Arrow x1={58 + i * 56} y1={64} x2={76 + i * 56} y2={64} c="g" />}
          </g>
        ))}
        <Txt x="320" y="104" size={9.5} color="var(--s-accent)">база</Txt>
        <Txt x="180" y="140" mono size={12}>каждый вызов приближает к базе</Txt>
      </G>
      <G o={step === 2 ? 1 : 0}>
        <Pill x={90} y={56} w={130} h={32} text="гипотеза индукции" stroke="var(--s-blue)" size={10} />
        <Txt x="180" y="60" mono size={12}>или</Txt>
        <Pill x={270} y={56} w={130} h={32} text="инвариант цикла" stroke="var(--s-accent)" size={10} />
        <Txt x="180" y="110" size={10.5}>утверждение, остающееся верным на каждом шаге</Txt>
      </G>
      <G o={step === 3 ? 1 : 0}>
        <Txt x="180" y="46" mono size={15} color="var(--s-accent)">T(n) = (стоимость уровня) × (число уровней)</Txt>
        <Pill x={110} y={96} w={130} h={32} text="сколько стоит уровень" stroke="var(--s-blue)" size={9.5} />
        <Txt x="180" y="100" mono size={14}>×</Txt>
        <Pill x={250} y={96} w={130} h={32} text="сколько уровней" stroke="var(--s-amber)" size={9.5} />
      </G>
      <G o={step >= 4 ? 1 : 0}>
        {["сформулировал базу?", "что верно на каждом шаге?", "какая рекуррентность?"].map((t, i) => (
          <Pill key={t} x={180} y={34 + i * 38} w={230} h={28} text={`${i + 1}. ${t}`} stroke="var(--s-accent)" size={10.5} />
        ))}
        <Txt x="180" y="150" mono size={11} color="var(--s-accent)">«кажется, работает» → «работает, и вот почему»</Txt>
      </G>
    </Steps>
  );
}
