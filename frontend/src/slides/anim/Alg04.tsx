const byVal = (
  vals: (string | number)[],
  {
    x0 = 50,
    cw = 36,
    y = 70,
    w,
    h = 28,
    c = {},
    sub,
    size = 11.5,
    o = {},
  }: {
    x0?: number;
    cw?: number;
    y?: number;
    w?: number;
    h?: number;
    c?: Record<string | number, string>;
    sub?: (i: number) => string | number;
    size?: number;
    o?: Record<string | number, number>;
  } = {},
): SceneItem[] =>
  vals.map((v: string|number, i: number): SceneItem => ({
    t: "cell",
    id: `v${v}`,
    x: x0 + cw * i,
    y,
    w: w ?? cw - 4,
    h,
    text: v,
    c: c[v] ?? c[i] ?? "m",
    size,
    sub: sub ? sub(i) : undefined,
    o: o[v] ?? 1,
  }));

