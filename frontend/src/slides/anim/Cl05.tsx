const cells = (prefix: string, x0: number, y: number, vals: (string|number)[], c = "b", w = 34, hl: number[] = []) =>
  vals.map((v, i) =>
    Box(
      `${prefix}${i}`,
      x0 + i * (w + 2),
      y,
      w,
      26,
      `${v}`,
      v === "" ? "m" : hl.includes(i) ? "y" : c,
      { size: 9.5, o: v === "" ? 0.5 : 1 },
    ),
  );

