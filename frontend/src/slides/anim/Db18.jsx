// 7. Уровни изоляции
const LV = [
  "READ UNCOMMITTED",
  "READ COMMITTED",
  "REPEATABLE READ",
  "SERIALIZABLE",
];
const AN = ["грязное", "неповт.", "фантом"];
const MATRIX = [
  [1, 1, 1],
  [0, 1, 1],
  [0, 0, 1],
  [0, 0, 0],
];
const grid = (upto) => [
  ...AN.map((a, j) => Tx(`h${j}`, 200 + j * 56, 22, a, { size: 8.5 })),
  ...LV.flatMap((l, i) => [
    Tx(`l${i}`, 20, 52 + i * 30, l, { size: 8.5, mono: true, anchor: "start" }),
    ...AN.map((_, j) =>
      Box(
        `c${i}${j}`,
        200 + j * 56,
        52 + i * 30,
        48,
        22,
        i < upto ? (MATRIX[i][j] ? "возможно" : "нет") : "",
        i < upto ? (MATRIX[i][j] ? "r" : "g") : "m",
        { size: 8, o: i < upto ? 1 : 0.25 },
      ),
    ),
  ]),
];
