/* Глава 23 книги «Базы данных»: шардирование. */

const sh = (id: string, x: number, y: number, text: string, c = "b", w = 66) =>
  Box(id, x, y, w, 30, text, c, { size: 9 });
const dots = (prefix: string, x0: number, y: number, n: number, c = "b", w = 14) =>
  Array.from({ length: n }, (_, i) =>
    Box(`${prefix}${i}`, x0 + i * (w + 2), y, w, 14, "", c, { size: 7 }),
  );

