// 5. Консистентное хеширование
const ringPos = (a: number) => [180 + 55 * Math.cos(a), 80 + 55 * Math.sin(a)];
const rn = (id: string, a: number, text: string, c = "b") => {
  const [x, y] = ringPos(a);
  return Box(id, x, y, 38, 22, text, c, { size: 8.5 });
};
