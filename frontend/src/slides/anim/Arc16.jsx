// 3. Форматы команд
const FM = {
  R: [
    ["funct7", 7],
    ["rs2", 5],
    ["rs1", 5],
    ["funct3", 3],
    ["rd", 5],
    ["opcode", 7],
  ],
  I: [
    ["imm[11:0]", 12],
    ["rs1", 5],
    ["funct3", 3],
    ["rd", 5],
    ["opcode", 7],
  ],
  S: [
    ["imm[11:5]", 7],
    ["rs2", 5],
    ["rs1", 5],
    ["funct3", 3],
    ["imm[4:0]", 5],
    ["opcode", 7],
  ],
};
const CLR = {
  funct7: "m",
  funct3: "m",
  rs2: "y",
  rs1: "b",
  rd: "g",
  opcode: "r",
  "imm[11:0]": "r",
  "imm[11:5]": "r",
  "imm[4:0]": "r",
};
const fmt = (k, ex) => {
  let x = 20;
  const items = [
    Tx("t", 180, 20, `формат ${k}: ${ex}`, { size: 10, mono: true }),
  ];
  FM[k].forEach(([n, w], i) => {
    const px = (w / 32) * 320;
    items.push(
      Box(`f${i}`, x + px / 2, 66, px - 2, 34, `${n}\n${w}`, CLR[n] ?? "m", {
        size: 8,
      }),
    );
    x += px;
  });
  items.push(
    Tx("n1", 20, 120, "31", { size: 8.5, mono: true, anchor: "start" }),
    Tx("n2", 340, 120, "0", { size: 8.5, mono: true, anchor: "end" }),
  );
  return items;
};
