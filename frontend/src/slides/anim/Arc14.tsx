// 6. Блок исполнения
const exec = (acc: number, k: number, useAdd: number, ld: number) => {
  const nx = ld ? (useAdd ? (acc + k) % 4 : k) : acc;
  return [
    Box("acc", 60, 76, 80, 40, `ACC = ${acc}`, "b", { size: 11 }),
    Box("op", 190, 76, 80, 40, useAdd ? "ACC + k" : "k", "m", { size: 11 }),
    Box(
      "fl",
      300,
      76,
      80,
      40,
      `Z = ${nx === 0 ? 1 : 0}`,
      nx === 0 ? "y" : "m",
      { size: 11 },
    ),
    pl(
      "w1",
      [
        [100, 76],
        [150, 76],
      ],
      "m",
    ),
    pl(
      "w2",
      [
        [230, 76],
        [260, 76],
      ],
      "m",
    ),
    Tx("n", 180, 130, ld ? `по фронту ACC ← ${nx}` : "ACC не меняется", {
      size: 10,
      mono: true,
      c: ld ? "g" : "y",
    }),
    Tx("k", 190, 52, `k = ${k}`, { size: 9, mono: true }),
  ];
};
