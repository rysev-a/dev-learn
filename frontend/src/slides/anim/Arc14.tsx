// 3. Регистр с записью
const reg2 = (ld: number, d: number, q: number) => {
  const nq = ld ? d : q;
  return [
    ...[1, 0].flatMap((i) => [
      ...mux(`m${i}`, 130, 40 + (1 - i) * 56, 36, 44, "b", "MUX"),
      Box(`f${i}`, 220, 40 + (1 - i) * 56, 56, 34, "DFF", "b", { size: 10 }),
      bit(`d${i}`, 36, 40 + (1 - i) * 56, (d >> i) & 1),
      Tx(`dl${i}`, 36, 24 + (1 - i) * 56, `D${i}`, { size: 8 }),
      pl(
        `w${i}`,
        [
          [48, 40 + (1 - i) * 56],
          [112, 40 + (1 - i) * 56],
        ],
        lv((d >> i) & 1),
      ),
      pl(
        `x${i}`,
        [
          [148, 40 + (1 - i) * 56],
          [192, 40 + (1 - i) * 56],
        ],
        lv((nq >> i) & 1),
      ),
      pl(
        `o${i}`,
        [
          [248, 40 + (1 - i) * 56],
          [300, 40 + (1 - i) * 56],
        ],
        lv((nq >> i) & 1),
      ),
      bit(`q${i}`, 316, 40 + (1 - i) * 56, (nq >> i) & 1),
      Tx(`ql${i}`, 340, 40 + (1 - i) * 56, `Q${i}`, {
        size: 8,
        anchor: "start",
      }),
    ]),
    bit("ld", 130, 148, ld),
    Tx("ll", 146, 148, "LD", { size: 8.5, anchor: "start" }),
    pl(
      "wl",
      [
        [130, 138],
        [130, 110],
      ],
      lv(ld),
    ),
    pl(
      "wl2",
      [
        [130, 110],
        [130, 66],
      ],
      lv(ld),
      { o: 0.0 },
    ),
    Tx(
      "n",
      230,
      148,
      ld
        ? `по фронту записано ${d.toString(2).padStart(2, "0")}`
        : "по фронту хранит прежнее",
      { size: 9, c: ld ? "g" : "y" },
    ),
  ];
};
