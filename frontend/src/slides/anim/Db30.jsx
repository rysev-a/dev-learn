/* Глава 30 книги «Базы данных»: миграции и резервные копии. */

const nd = (id, x, y, text, c = "b", w = 66) =>
  Box(id, x, y, w, 28, text, c, { size: 9 });
const sm = (id, x, y, text, c = "b", w = 40) =>
  Box(id, x, y, w, 20, text, c, { size: 8 });
const steps = (labels, y, c = "g", w = 70, x0 = 44, gap = 90) => [
  ...labels.map((t, i) =>
    nd(`s${i}`, x0 + i * gap, y, t, typeof c === "function" ? c(i) : c, w),
  ),
  ...labels
    .slice(1)
    .map((_, i) =>
      arrow(
        `a${i}`,
        x0 + i * gap + w / 2,
        y,
        x0 + (i + 1) * gap - w / 2,
        y,
        "m",
      ),
    ),
];

