// 4. Хаффман
const FREQ = [
  ["A", 45],
  ["B", 13],
  ["C", 12],
  ["D", 16],
  ["E", 9],
  ["F", 5],
] as const;
interface HuffStep {
  q: { k: string; v: number }[];
  t: string;
}
function huffSteps(): HuffStep[] {
  let q: { k: string; v: number }[] = FREQ.map(([k, v]) => ({ k, v }));
  const steps: HuffStep[] = [
    { q: [...q].sort((a, b) => a.v - b.v), t: "частоты символов" },
  ];
  while (q.length > 1) {
    q.sort((a, b) => a.v - b.v);
    const [a, b] = q;
    q = [{ k: a!.k + b!.k, v: a!.v + b!.v }, ...q.slice(2)];
    steps.push({
      q: [...q].sort((x, y) => x.v - y.v),
      t: `сливаем ${a!.k}${a!.v} и ${b!.k}${b!.v} → ${a!.v + b!.v}`,
    });
  }
  return steps;
}
