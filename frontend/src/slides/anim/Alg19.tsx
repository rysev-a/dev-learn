// 10. Коммивояжёр и эвристики
const PTS: [number, number][] = [
  [50, 50],
  [120, 36],
  [200, 60],
  [280, 40],
  [300, 120],
  [210, 130],
  [130, 118],
  [60, 124],
];
const near = (() => {
  const left = new Set(PTS.keys());
  const order = [0];
  left.delete(0);
  while (left.size) {
    const [cx, cy] = PTS[order[order.length - 1]!]!;
    let best: [number, number] | null = null;
    for (const i of left) {
      const d = Math.hypot(PTS[i]![0] - cx, PTS[i]![1] - cy);
      if (best === null || d < best[1]) best = [i, d];
    }
    if (!best) break;
    order.push(best[0]);
    left.delete(best[0]);
  }
  return order;
})();
const pathD = (order: number[]) =>
  order.map((i, k) => `${k ? "L" : "M"}${PTS[i]![0]} ${PTS[i]![1]}`).join(" ") +
  ` L${PTS[order[0]!]![0]} ${PTS[order[0]!]![1]}`;
