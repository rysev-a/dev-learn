/* Глава 4 книги «Архитектура компьютера»: числа в компьютере. */

const bits = (id: string, s: string, x0: number, y: number, cw = 26, c: string | ((i: number) => string) = "m", extra: Extra = {}): SceneItem[] =>
  s
    .split("")
    .map((b, i) =>
      Box(
        `${id}${i}`,
        x0 + i * cw,
        y,
        cw - 3,
        24,
        b,
        typeof c === "function" ? c(i) : c,
        { size: 12, ...extra },
      ),
    );

