// 5. Метки и циклы
const loop = (hl, cnt) => [
  code(
    "c",
    20,
    24,
    [
      "      li   r1, 3",
      "цикл: addi r1, r1, -1",
      "      bnez r1, цикл",
      "      hlt",
    ],
    hl,
    { w: 200 },
  ),
  Box("r1", 300, 40, 90, 28, `r1 = ${cnt}`, cnt === 0 ? "y" : "g", {
    size: 10.5,
  }),
  ...(hl === 2
    ? [
        pl(
          "jmp",
          [
            [236, 60],
            [250, 60],
            [250, 38],
            [236, 38],
          ],
          cnt ? "g" : "m",
          { w: 1.8 },
        ),
        Tx(
          "t",
          300,
          100,
          cnt ? "r1 ≠ 0: прыгаем\nна метку цикл" : "r1 = 0: идём дальше",
          { size: 9.5, c: cnt ? "g" : "y" },
        ),
      ]
    : []),
];
