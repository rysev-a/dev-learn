/* Глава 15 книги «Архитектура компьютера»: ассемблер процессора Мини-8. */

const Box = (id, x, y, w, h, text, c = "m", extra = {}) =>
  cell(id, x, y, text, c, { w, h, size: 9.5, ...extra });
const arrow = (id, x1, y1, x2, y2, c = "m") => ({
  t: "line",
  id,
  x1,
  y1,
  x2,
  y2,
  c,
  arrow: true,
});
const code = (id, x, y, lines, hl, extra = {}) => ({
  t: "code",
  id,
  x,
  y,
  lines,
  hl,
  size: 10,
  lh: 14,
  w: 150,
  ...extra,
});
const regs = (vals, hl = -1) =>
  vals.map((v, i) =>
    Box(
      `r${i}`,
      30 + i * 44,
      128,
      38,
      28,
      `r${i}\n${v}`,
      i === hl ? "g" : "m",
      { size: 9 },
    ),
  );

// 1. Текст → машинный код
const asm = (n) => [
  Box("src", 70, 40, 120, 26, "li r1, 72", n === 0 ? "g" : "b", { size: 11 }),
  ...(n >= 1
    ? [
        arrow("a", 70, 56, 70, 78, "g"),
        ...["0001", "001", "001", "001000"].map((f, i) =>
          Box(
            `f${i}`,
            [44, 98, 140, 220][i],
            100,
            [50, 50, 50, 90][i],
            26,
            f,
            "g",
            { size: 10 },
          ),
        ),
        Tx("fl", 140, 124, "код    A     B       C", { size: 8.5, mono: true }),
      ]
    : []),
  ...(n >= 2
    ? [
        Tx("hx", 290, 40, "= 0x1248\nмашинное слово", {
          size: 9.5,
          mono: true,
          c: "g",
        }),
      ]
    : []),
];
export const V01 = scene({
  labels: ["Ассемблер", "Поля", "Машинное слово"],
  caption: [
    "У команды есть короткое имя, у регистров — названия; ассемблер переводит текст в числа",
    "Шестнадцать бит делятся на поля: код операции, номера регистров, число",
    "Процессор видит только это слово; человек читает ассемблерный текст",
  ],
  frames: [asm(0), asm(1), asm(2)],
});

