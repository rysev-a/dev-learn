const ST = ["IF", "ID", "EX", "MEM", "WB"];

// Диаграмма конвейера: rows[i] = {start, bubbles: набор тактов-пузырей, c} ; клетки стадий
interface PipeRow {
  start: number;
  c?: string;
  stall?: [number, number];
}
const pipe = (
  rows: PipeRow[],
  upto = 99,
  opts: { x0?: number; cw?: number; y0?: number; ch?: number; labels?: string[] } = {},
): SceneItem[] => {
  const { x0 = 86, cw = 34, y0 = 34, ch = 24, labels } = opts;
  const out: SceneItem[] = [];
  rows.forEach((r, i) => {
    out.push(
      Tx(`n${i}`, 24, y0 + i * ch, labels?.[i] ?? `команда ${i + 1}`, {
        size: 8,
        anchor: "start",
      }),
    );
    let t = r.start;
    ST.forEach((s, k) => {
      while (r.stall && r.stall[0] === k && r.stall[1] > 0) {
        for (let b = 0; b < r.stall[1]; b++) {
          out.push(
            Box(
              `b${i}_${k}_${b}`,
              x0 + t * cw,
              y0 + i * ch,
              cw - 3,
              ch - 4,
              "·",
              "y",
              { size: 9, o: t < upto ? 1 : 0 },
            ),
          );
          t += 1;
        }
        r.stall = [k, 0];
      }
      out.push(
        Box(
          `c${i}_${k}`,
          x0 + t * cw,
          y0 + i * ch,
          cw - 3,
          ch - 4,
          s,
          r.c ?? "b",
          { size: 8.5, o: t < upto ? 1 : 0 },
        ),
      );
      t += 1;
    });
  });
  return out;
};
const clockMarks = (n: number, cw = 34, x0 = 86, y = 14) =>
  Array.from({ length: n }, (_, t) =>
    Tx(`t${t}`, x0 + t * cw, y, String(t + 1), { size: 8, mono: true }),
  );

