const laundry = (n: number) => {
  const names = ["стирка", "сушка", "глажка"];
  const items = [];
  const rows = n === 0 ? 2 : 4;
  for (let r = 0; r < rows; r++)
    names.forEach((nm, k) => {
      const t = n === 0 ? r * 3 + k : r + k;
      items.push(
        Box(
          `c${r}${k}`,
          60 + t * 40,
          40 + r * 26,
          36,
          20,
          nm,
          n === 0 ? "m" : r === 0 ? "g" : "b",
          { size: 7.5 },
        ),
      );
    });
  items.push(
    Tx(
      "n",
      180,
      36 + rows * 26 + 20,
      n === 0
        ? "по очереди: 3 часа на каждый комплект"
        : "после начальной задержки — комплект каждый час",
      { size: 9.5, c: n === 0 ? "r" : "g" },
    ),
  );
  return items;
};
