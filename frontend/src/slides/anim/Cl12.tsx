const cells = (prefix: string, x0: number, y: number, vals: (number | string)[], c = "b", w = 34, hl: number[] = [], cols: Record<string | number, string> = {}) =>
  vals.map((v, i) =>
    Box(
      `${prefix}${i}`,
      x0 + i * (w + 2),
      y,
      w,
      26,
      `${v}`,
      v === "" ? "m" : (cols[i] ?? (hl.includes(i) ? "y" : c)),
      { size: 9.5, o: v === "" ? 0.5 : 1 },
    ),
  );

