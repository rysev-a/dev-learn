const cellRow = (prefix, x0, y, items) =>
  items.map(([w, text, c], i) => {
    const x = x0 + items.slice(0, i).reduce((a, it) => a + it[0], 0) + w / 2;
    return Box(`${prefix}${i}`, x, y, w - 2, 26, text, c, { size: 8.5 });
  });
