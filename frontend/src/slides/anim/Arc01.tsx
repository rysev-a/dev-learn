// 2. Миллиарды транзисторов
const dots = (n: number, cols: number, dx: number, dy: number, x0: number, y0: number, r: number): SceneItem[] =>
  Array.from({ length: 150 }, (_, i): SceneItem => {
    const col = i % cols;
    const row = Math.floor(i / cols);
    return {
      t: "dot",
      id: `d${i}`,
      x: x0 + col * dx,
      y: y0 + row * dy,
      r,
      text: "",
      c: "b",
      o: i < n ? 1 : 0,
    };
  });
