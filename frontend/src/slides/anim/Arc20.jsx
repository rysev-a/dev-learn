// 10. Выбор жертвы
const clock = (hand) => {
  const bitsA = [1, 1, 0, 1, 0, 1];
  return [
    ...bitsA.map((b, i) => {
      const a = (i / 6) * Math.PI * 2 - Math.PI / 2;
      return Box(
        `c${i}`,
        180 + Math.cos(a) * 48,
        78 + Math.sin(a) * 48,
        36,
        24,
        `страница ${i}\nA=${hand > i && b ? 0 : b}`,
        i === hand ? "y" : bitsA[i] ? "m" : "b",
        { size: 7 },
      );
    }),
    Tx("n", 180, 78, hand >= 2 ? "жертва: A = 0" : "A = 1: второй шанс", {
      size: 9,
      c: hand >= 2 ? "r" : "y",
    }),
  ];
};
