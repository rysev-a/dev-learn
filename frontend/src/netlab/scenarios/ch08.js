/* Глава 8 «Надёжность и управление перегрузкой»: окно приёма, алгоритм при потерях, размер очереди. */
import { device, iface, link, makeState } from "../model.js";

const gw = (via) => [{ dst: "0.0.0.0/0", via, dev: null }];
const host = (id, name, x, y, ip, via, extra = {}) =>
  device(id, "host", name, x, y, { ifaces: [iface("eth0", { ip })], routes: via ? gw(via) : [], ...extra });
const server = (id, name, x, y, ip, via, extra = {}) =>
  device(id, "server", name, x, y, { ifaces: [iface("eth0", { ip })], routes: via ? gw(via) : [], ...extra });
const router = (id, name, x, y, a, b, extra = {}) =>
  device(id, "router", name, x, y, { ifaces: [iface("eth0", { ip: a }), iface("eth1", { ip: b })], ...extra });

